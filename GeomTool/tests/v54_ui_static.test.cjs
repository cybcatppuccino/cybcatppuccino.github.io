'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8'),app=fs.readFileSync(path.join(root,'assets/app.js'),'utf8');
const p=html.match(/<div class="pretty-syntax-guide" id="pretty-syntax-panel" hidden>([\s\S]*?)<\/div>\s*<p id="pretty-condition-feedback"/);
assert.ok(p,'syntax panel included and initially hidden');
assert.equal((p[1].match(/<section>/g)||[]).length,7,'seven rules visible on toggle');
assert.ok(/id="pretty-syntax-toggle"[^>]*aria-expanded="false"/.test(html),'accessible question-mark button');
assert.ok(!html.includes('pretty-suggestions')&&!html.includes('pretty-condition-help'),'no old datalist or live syntax hints');
assert.ok(!app.includes('prettySyntaxTips'),'no eager per-keyword help');
assert.ok(app.includes('toggle.onclick=()'),'question-mark toggles help');
assert.ok(html.includes('GeomTool v5.4'),'version correct');
console.log('PASS v5.4 static UI — seven rules, ? control, no datalist');
