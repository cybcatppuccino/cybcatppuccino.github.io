/* v3.5 regression: angle math, kernel console construction, command catalog. */
'use strict';
const assert=require('node:assert/strict');
const Expr=require('../assets/expression.js');
const Console=require('../assets/console.js');
const {Kernel,METHODS,runText}=require('../assets/kernel.js');
const near=(a,b)=>assert.ok(Math.abs(a-b)<=1e-9,`${a} != ${b}`);
for(const s of ['π','pi','PI'])near(Expr.parse(s),Math.PI);
for(const s of ['2pi/3','2π/3','2×π÷3','2*pi/3'])near(Expr.parse(s),2*Math.PI/3);
near(Expr.parse('sqrt2'),Math.SQRT2);
near(Expr.parse('2(3+4)'),14);
near(Expr.parse('-sqrt(2)'),-Math.SQRT2);
assert.throws(()=>Expr.parse('pi/0'),/无效/);
assert.throws(()=>Expr.parse('2pi@3'),/不支持/);
assert.equal(Expr.convertAngle('60','deg','rad'),'π/3');
assert.equal(Expr.convertAngle('120','deg','rad'),'2π/3');
assert.equal(Expr.convertAngle('90','deg','rad'),'π/2');
assert.equal(Expr.convertAngle('π','rad','deg'),'180');
assert.equal(Expr.convertAngle('2pi/3','rad','deg'),'120');
assert.throws(()=>Expr.convertAngle('oops','deg','rad'),/未知/);
const k=new Kernel();runText(k,'point O 0 0');runText(k,'point P 2 0');
runText(k,'rotate R P O 2π/3 rad');
near(k.geom('R').x,-1);near(k.geom('R').y,Math.sqrt(3));
runText(k,'rotate S P O 120 deg');near(k.geom('S').y,k.geom('R').y);
runText(k,'rotate T P O pi/2 rad');near(k.geom('T').x,0);near(k.geom('T').y,2);
runText(k,'homothety H P O -sqrt(2)');near(k.geom('H').x,-2*Math.SQRT2);
runText(k,'circler c O 2pi/3');near(k.geom('c').r,2*Math.PI/3);
runText(k,'move P pi 0');near(k.geom('P').x,Math.PI);
runText(k,'hide P');assert.equal(k.node('P').style.visible,false);
assert.equal(k.node('P').valid,true,'hidden parent must still be valid');
runText(k,'show P');assert.equal(k.node('P').style.visible,true);
const sys=k._create({op:'referencePoint',id:'GTREF_test',label:'参考',params:{x:0,y:0},style:{system:true,visible:true,reference:true}});
k.execute({op:'style',id:sys.id,style:{visible:false}});assert.equal(k.node(sys.id).style.visible,false);
assert.throws(()=>k.execute({op:'delete',id:sys.id}),/系统参考/);
assert.throws(()=>k.execute({op:'rename',id:sys.id,label:'XX'}),/名称无效/);
Console.registerMethods(METHODS);
assert.ok(Console.commands.length>80,'All kernel methods included in detailed categorized help');
for(const q of ['弧度','位似','隐藏','关系','导入','旋转','beautify'])assert.ok(Console.search(q).length>0,'missing command search '+q);
assert.ok(Console.search('rotate').some(x=>x.syntax.startsWith('rotate ')));
assert.deepEqual(Console.words('doc "我的 几何图"'),['doc','我的 几何图']);
console.log(`PASS v3.5 console/expression: ${Console.commands.length} help entries; radian inputs, equivalent unit conversion, systems/hidden and kernel text construction`);
